import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, '../..');
const artifactPath = resolve(repoRoot, 'out/MemeToken.sol/MemeToken.json');
const outputPath = resolve(scriptDir, '../src/generated/memeTokenBytecode.ts');

const artifact = JSON.parse(readFileSync(artifactPath, 'utf8'));
const bytecode = artifact.bytecode?.object;

if (typeof bytecode !== 'string' || !bytecode.startsWith('0x')) {
  throw new Error(`MemeToken creation bytecode not found in ${artifactPath}`);
}

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(
  outputPath,
  [
    '// Generated by scripts/sync-meme-token-bytecode.mjs.',
    '// Keep this in sync with out/MemeToken.sol/MemeToken.json after contract changes.',
    `export const MEME_TOKEN_CREATION_BYTECODE = '${bytecode}' as const;`,
    '',
  ].join('\n'),
);

console.log(`Synced MemeToken creation bytecode to ${outputPath}`);
